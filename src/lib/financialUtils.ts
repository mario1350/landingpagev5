/**
 * Get the LUMA rate for a specific date
 */
export function getLUMARate(date: Date): number {
  const yearMonth = date.toISOString().slice(0, 7); // Format: YYYY-MM
  const rate = lumaRates.find(r => r.date === yearMonth);
  
  if (!rate) {
    // If rate not found, use the last known rate
    return lumaRates[lumaRates.length - 1].rate;
  }
  
  return rate.rate;
}

/**
 * Calculate monthly bill based on consumption and date
 */
export function calculateMonthlyBill(consumption: number, date: Date): number {
  const rate = getLUMARate(date);
  return consumption * rate;
}

/**
 * Calculate yearly bills with projected rates
 */
export function calculateYearlyBills(
  monthlyConsumption: number,
  startDate: Date = new Date(),
  years: number = 25
): {
  yearlyBills: number[];
  totalBill: number;
} {
  const yearlyBills: number[] = [];
  let totalBill = 0;
  
  for (let year = 0; year < years; year++) {
    let yearlyTotal = 0;
    
    for (let month = 0; month < 12; month++) {
      const date = new Date(startDate);
      date.setFullYear(date.getFullYear() + year);
      date.setMonth(date.getMonth() + month);
      
      const monthlyBill = calculateMonthlyBill(monthlyConsumption, date);
      yearlyTotal += monthlyBill;
    }
    
    yearlyBills.push(yearlyTotal);
    totalBill += yearlyTotal;
  }
  
  return {
    yearlyBills,
    totalBill
  };
}

/**
 * Calculate monthly savings compared to original bill
 */
export function calculateMonthlySavings(
  originalConsumption: number,
  remainingConsumption: number,
  date: Date
): number {
  const rate = getLUMARate(date);
  const originalBill = originalConsumption * rate;
  const newBill = remainingConsumption * rate;
  
  return originalBill - newBill;
}
